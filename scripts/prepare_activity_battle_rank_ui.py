    sources[enum.relative_to(ROOT).as_posix()] = hashlib.sha256(enum.read_bytes()).hexdigest()
    target = DESTINATION / enum.name
    target.write_text(enum.read_text('utf8').replace('namespace Common;', 'namespace Zjcs.Official.ActivityRankUI\n{') + '\n}\n', 'utf8', newline='\n')
    for output in (target, metadata(target)):
        outputs[output.relative_to(ROOT).as_posix()] = hashlib.sha256(output.read_bytes()).hexdigest()
    for name in ('TeamTopContentFirstItem.cs', 'TeamTopContentDataActivityDomainBoss.cs', 'AppearanceSystem/NpcAppearance.cs',
                 'RuleDialog.cs', 'TipInfo.cs', 'AppearanceUIPartHandler.cs', 'PartSlot.cs',
                 'SkeletonGraphicSeparator.cs', 'AppearanceSkeletonPart.cs'):
        path = CLIENT / name
        if not path.exists(): path = CLIENT / name.replace('/', '.')
