def method(text, name):
    match = re.search(r'\tpublic static [^\n]+\b' + re.escape(name) + r'\([^\n]*\)\n\t\{', text)
    if not match:
        raise ValueError('Original UI helper missing: ' + name)
    end, depth = match.end(), 1
    while depth:
        depth += (text[end] == '{') - (text[end] == '}')
        end += 1
    return re.sub(r'^\s*//IL_.*\n', '\n', text[match.start():end], flags=re.M)


