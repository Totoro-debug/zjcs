"""Migrate source attachment, animator and reward-count views.

World-stage queries are selected verbatim shared methods on explicit read-model
boundaries. They consume original state/award data; they do not execute rewards,
advance stages or invent server-side results.
"""
from pathlib import Path
import json
import re

from official_apk import ROOT
from prepare_unity_map13_sources import encode, sha, write
from prepare_unity_story_attachment_runtime import CODE, record, method
from prepare_unity_story_playable_runtime import logging_adapter
from prepare_unity_map13_prop_parts import meta

DEST = ROOT / 'unity/Assets/Game/Runtime/Official/World/Map13EntityStateViews'
NAMESPACE = 'Zjcs.Official.World.Map13EntityStateViews'
RECEIPT = ROOT / 'assets/reference/official-map/map13-entity-state-views-source-manifest.json'


def build():
    manifest = json.loads((CODE.parent / 'code-manifest.json').read_bytes())
    assemblies = [CODE / 'managed/decoded' / n for n in ('Assembly-CSharp.dll', 'Console.dll')]
    for p in assemblies:
        if sha(p.read_bytes()) != manifest['assemblies'][p.name]['decoded_sha256']:
            raise ValueError('Selected original state-view assembly changed: ' + p.name)
    inputs, outputs, adaptations = [], [], []

    def emit(name, text):
        p = DEST / (name + '.cs')
        write(p, ('// Migrated source application/query code; see map13-entity-state-views receipt.\n' + text).encode())
        meta(p, 'MonoImporter')
        outputs.extend([p, Path(str(p) + '.meta')])

    for name in ['ECAttachAgentView', 'ECAnimatorView', 'ECMapAwardItemCountSwitcherView']:
        p = CODE / 'client-source' / (name + '.cs'); inputs.append(p)
        text = p.read_text(encoding='utf-8-sig')
        text = re.sub(r'(?m)^using (?:System|Common|Framework(?:\.[\w.]+)?);\n', '', text)
        text, diagnostics = logging_adapter(text)
        split = text.index('public class ')
        header = ('using Object = UnityEngine.Object;\nusing System;\n'
                  'using Zjcs.Official.EntityViews;\nusing Zjcs.Official.StoryAttachment;\n'
                  'using Zjcs.Official.StoryAnimation;\nusing Zjcs.Official.StorySourceFade;\n')
        if name == 'ECMapAwardItemCountSwitcherView':
            header += ('using WorldStageComponent = ' + NAMESPACE + '.Map13WorldStageQuery;\n'
                       'using StageResultAwardItemComponent = ' + NAMESPACE + '.Map13AwardItemQuery;\n')
        text = header + text[:split] + 'namespace ' + NAMESPACE + '\n{\n[Serializable]\n' + text[split:] + '\n}\n'
        text = '\n'.join(line.rstrip() for line in text.splitlines()) + '\n'
        emit(name, text)
        adaptations.append(dict(source=name, diagnostic_blocks=diagnostics,
                                serializable_for_native_managed_reference=True,
                                namespace_and_explicit_read_queries=True))

    for name in ['StageComponentType', 'StageCompCfg', 'SubStageStateInfo', 'StageStateInfo', 'StageSingleAwardItemInfo']:
        p = CODE / 'common-source/Common' / (name + '.cs'); inputs.append(p)
        text = p.read_text(encoding='utf-8-sig')
        text = text.replace('using MessagePack;\n', '')
        text = re.sub(r'(?m)^\s*\[(?:MessagePackObject|Key)\([^\n]*\)\]\n', '\n', text)
        text = text.replace('namespace Common;', 'namespace ' + NAMESPACE + '\n{') + '\n}\n'
        emit(name, text)

    stage = CODE / 'common-source/Common/WorldStageComponent.cs'
    award = CODE / 'common-source/Common/StageResultAwardItemComponent.cs'
    inputs.extend([stage, award])
    stage_text = stage.read_text(encoding='utf-8-sig'); award_text = award.read_text(encoding='utf-8-sig')
    stage_methods = [method(stage_text, sig) for sig in [
        'public virtual int GetStateComponentIndex(', 'public StageStateInfo GetCurStateInfo()']]
    award_method = method(award_text, 'public bool TryGetAwardItemInfo(')
    emit('Map13WorldStageQuery', '''using System;
using System.Collections.Generic;
namespace ''' + NAMESPACE + '''
{
    // Explicit source-consumption data boundary. Only the original shared
    // state queries below are migrated; this is not the WorldStage executor.
    [Serializable] public sealed class Map13StageStateQueryData
    { public List<StageStateInfo> StateInfos = new List<StageStateInfo>(); }
    public class Map13WorldStageQuery
    {
        public int State;
        public Map13StageStateQueryData Info;
''' + '\n\n'.join(stage_methods) + '\n    }\n}\n')
    emit('Map13AwardItemQuery', '''using System;
using System.Collections.Generic;
namespace ''' + NAMESPACE + '''
{
    // Explicit config/server-result consumption boundary. The source fallback
    // and index rules remain verbatim; no award is generated by this reader.
    [Serializable] public sealed class Map13AwardItemQueryData
    { public List<StageSingleAwardItemInfo> AwardItemInfos; }
    public sealed class Map13AwardItemQuery
    {
        public Map13AwardItemQueryData Info;
        public List<StageSingleAwardItemInfo> AwardItemInfos;
''' + award_method + '\n    }\n}\n')

    asm = DEST / (NAMESPACE + '.asmdef')
    write(asm, encode(dict(name=NAMESPACE, rootNamespace=NAMESPACE, references=[
        'Zjcs.Official.EntityViews', 'Zjcs.Official.StoryAttachment',
        'Zjcs.Official.StoryAnimation', 'Zjcs.Official.StorySourceFade'], autoReferenced=True)))
    meta(asm, 'AssemblyDefinitionImporter'); meta(DEST, folder=True)
    outputs.extend([asm, Path(str(asm) + '.meta'), Path(str(DEST) + '.meta')])
    reused = []
    for name in ['map14-entity-view-runtime-source-manifest.json', 'map14-story-attachment-runtime-source-manifest.json',
                 'map14-story-animator-runtime-source-manifest.json', 'map14-story-source-fade-runtime-source-manifest.json']:
        p = RECEIPT.with_name(name); receipt = json.loads(p.read_bytes()); inputs.append(p)
        for output in receipt['outputs']:
            q = ROOT / output['path']
            if sha(q.read_bytes()) != output['sha256']:
                raise ValueError('Reused application port changed: ' + str(q))
            inputs.append(q)
        reused.append(record(p))
    write(RECEIPT, encode(dict(manifest='871_156598', mapClassId=13,
        method='Copy three complete original EC views, original component enum and four state/award DTOs. Copy original shared GetStateComponentIndex/GetCurStateInfo/TryGetAwardItemInfo methods verbatim on explicit consumption-only readers; preserve branch/index/order semantics. Bind to the existing original EC lifecycle, attachment, animation controller and source fade ports.',
        coverage='Client attachment/animator/reward-count views and shared read queries only. Formal original entity, UI/state/event host, reward execution, map input/save and Windows Player still require integration.',
        assemblies=[record(p) for p in assemblies], inputs=[record(p) for p in sorted(set(inputs))],
        outputs=[record(p) for p in outputs], tools=[record(Path(__file__).resolve())],
        adaptations=adaptations, reused_application_ports=reused)))
    print('Migrated original state views and exact shared queries:', len(outputs), 'outputs')


if __name__ == '__main__':
    build()
