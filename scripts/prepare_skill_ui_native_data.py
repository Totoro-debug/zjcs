"""Bind compiled skill UI identity to the recorded JSON and check its native pack receipt."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "unity"
LAYOUT = "Assets/Official/Skills/skill-ui.json"
MANIFEST = "Assets/Official/Skills/source-manifest.json"
IDENTITY = ASSETS / "Assets/Game/Runtime/Offline/SkillAssets/OfficialSkillUiData.Identity.cs"
RECEIPT = ROOT / "assets/reference/skill-ui-native-data-source-manifest.json"


def digest(data):
    return hashlib.sha256(data).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--record", action="store_true", help="Generate the compiled identity; record the native bundle separately in Unity.")
    args = parser.parse_args()
    inputs = []
    for name in (LAYOUT, MANIFEST):
        raw = (ASSETS / name).read_bytes()
        inputs.append(dict(path=name, bytes=len(raw), sha256=digest(raw),
                           meta_sha256=digest((ASSETS / (name + ".meta")).read_bytes())))
    manifest = json.loads((ASSETS / MANIFEST).read_text(encoding="utf-8-sig"))
    row, = [value for value in manifest["files"] if value["path"] == LAYOUT]
    if (row["bytes"], row["sha256"]) != (inputs[0]["bytes"], inputs[0]["sha256"]):
        raise ValueError("The skill UI bytes differ from their recorded source manifest.")
    generated = """// Generated by scripts/prepare_skill_ui_native_data.py from the recorded official UI JSON.
namespace Zjcs.Offline.SkillAssets
{
    public static partial class OfficialSkillUiData
    {
        public const string LayoutSha256 = \"%s\";
    }
}
""" % inputs[0]["sha256"]
    if args.record:
        IDENTITY.write_text(generated, encoding="utf-8", newline="\n")
        print("Skill UI compiled identity prepared; build and record its native Windows pack in Unity.")
        return
    if IDENTITY.read_text(encoding="utf-8-sig") != generated:
        raise ValueError("The compiled UI identity is stale; review the recorded source before regenerating.")
    receipt = json.loads(RECEIPT.read_text(encoding="utf-8-sig"))
    if (receipt["schema"], receipt["unity_version"], receipt["target"], receipt["inputs"]) != (
        1, "2022.3.57f1c2", "StandaloneWindows64", inputs
    ):
        raise ValueError("The native UI pack inputs differ from their recorded source.")
    output = receipt["output"]
    if output["path"] != "Zjcs_Data/StreamingAssets/Skills/skill-ui-win64" or output["bytes"] <= 0 or len(output["sha256"]) != 64:
        raise ValueError("The native UI pack output receipt is incomplete.")
    print("Skill UI identity and native Windows pack source receipt verified:", inputs[0]["sha256"])


if __name__ == "__main__":
    main()
