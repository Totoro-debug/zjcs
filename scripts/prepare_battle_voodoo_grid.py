"""Restore the official substitute's grid mover from one selected source version."""
import hashlib
import json
from pathlib import Path

from official_apk import Apk, ROOT
from official_ec_codec import Formats
from official_map_codec import unpack
from official_tables import Constructors


OUTPUT = ROOT / "unity/Assets/Game/Runtime/Official/Combat/FightOfficialVoodooGridRules.cs"
PROOF = ROOT / "assets/reference/battle-rules/voodoo-grid-source-manifest.json"


def digest(raw):
    return hashlib.sha256(raw).hexdigest()


def record(path):
    return dict(path=path.relative_to(ROOT).as_posix(), sha256=digest(path.read_bytes()))


def build():
    apk = Apk()
    code = ROOT / ".tools/source-packages/current" / apk.version / "official-code"
    code_manifest = code.parent / "code-manifest.json"
    identity = json.loads(code_manifest.read_bytes())
    assembly, metadata = code / "managed/decoded/Console.dll", code / "global-metadata.dat"
    if (identity["manifest"] != apk.version
            or digest(assembly.read_bytes()) != identity["assemblies"]["Console.dll"]["decoded_sha256"]
            or digest(metadata.read_bytes()) != identity["metadata_sha256"]):
        raise ValueError("Official grid source identity differs from the selected manifest")
    constructors, formats = Constructors(code), Formats(code)
    inputs = []

    def payload(bundle, suffix):
        obj = apk.asset(bundle, suffix)
        raw = obj.read().m_Script.encode("utf-8", "surrogateescape")
        inputs.append(dict(asset=suffix, provenance=apk.provenance(obj),
                           payload_sha256=digest(raw), bytes=len(raw)))
        return raw

    rows = constructors.table(payload("config_luban_ec", "/EC/entity_grid_mover.g.bytes"),
                              "TbEntityGridMoverInfo")
    packet = payload("config_ec", "/FightOther_part1.g.bytes")
    entities = unpack(packet)[0]
    entity, = [components for parent, identity, components in entities if parent == 0 and identity == 4600]
    mover, = [formats.component(typ, data) for typ, data in entity
              if typ == "Common.FightGridMoverComponent"]
    legacy_path = ROOT / "unity/Assets/Official/Combat/battle-rules.json"
    legacy = json.loads(legacy_path.read_bytes())["entities"]["4600"]["FightGridMoverComponent"]
    if legacy != mover:
        raise ValueError("Substitute mover differs from the bound combat entity; migrate its binding first")
    key = mover["WalkableGroundTypeKey"]
    ground, = [row["GroundTypes"] for row in rows if row["Id"] == key]
    if not ground or any(not 0 <= value < 31 for value in ground):
        raise ValueError("Invalid official ground mask")
    if mover["WalkableGroundTypeServerOverrideKey"] != 0:
        raise ValueError("Server override requires a separate authoritative path")
    # GridMoverComponentInfo.GetMoveMask uses the ordinary table, excluding server overrides.
    source = '''// Generated by scripts/prepare_battle_voodoo_grid.py. Do not edit.
// Official mover and ground types are decoded together from manifest %s.
using System;

namespace Zjcs.Combat.Official
{
    internal static class FightOfficialVoodooGridRules
    {
        internal static int MoveMask(int entityId, int walkableKey, int overrideKey)
        {
            if (entityId != 4600 || walkableKey != %d || overrideKey != 0)
                throw new InvalidOperationException("Unbound official substitute mover: " + entityId);
            int mask = 0;
            foreach (int ground in new[] { %s }) mask |= 1 << ground;
            return mask;
        }
    }
}
''' % (apk.version, key, ", ".join(map(str, ground)))
    OUTPUT.write_text(source, encoding="utf-8", newline="\n")
    meta = Path(str(OUTPUT) + ".meta")
    guid = hashlib.md5(("zjcs-official:" + OUTPUT.relative_to(ROOT / "unity").as_posix()).encode()).hexdigest()
    meta.write_text("fileFormatVersion: 2\nguid: " + guid + "\nMonoImporter:\n"
                    "  externalObjects: {}\n  serializedVersion: 2\n  defaultReferences: []\n"
                    "  executionOrder: 0\n  icon: {instanceID: 0}\n  userData:\n"
                    "  assetBundleName:\n  assetBundleVariant:\n", encoding="ascii", newline="\n")
    names = {"GridMoverComponentInfo.cs", "EntityGridMoverInfoParser.cs", "GroundType.cs"}
    names.update(name + ".cs" for name in constructors.sources)
    sources = [record(code / "common-source/Common" / name) for name in sorted(names)]
    sources.extend(record(path) for path in sorted(set(formats.sources.values())))
    sources.extend([record(assembly), record(metadata)])
    proof = dict(manifest=apk.version, inputs=inputs, sources=sources,
                 code_manifest=record(code_manifest),
                 mover=mover, ground_types=ground,
                 bound_combat_entity=dict(**record(legacy_path), entity_id=4600,
                     component="FightGridMoverComponent", component_equal=True),
                 outputs=[record(OUTPUT), record(meta)], generator=record(Path(__file__)),
                 conversion="GridMoverComponentInfo.GetMoveMask: OR 1 << ground; compile the selected-version mover and its table together.")
    PROOF.write_text(json.dumps(proof, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")
    print("Official substitute grid:", apk.version, "key", key, "ground", ground)


if __name__ == "__main__":
    build()
