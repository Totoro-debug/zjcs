COMMON = CODE.parent / "common-source/Common"


def method(text, signature):
    start = text.index(signature)
    brace = text.index("{", start)
    depth = 1
    end = brace + 1
    while depth:
        depth += (text[end] == "{") - (text[end] == "}")
        end += 1
    return text[start:end]


def adapt(text):
    text = log_blocks(clean(text))
    text = re.sub(r'^using (?:Common|GConfig|Luban|Framework(?:\.[\w.]+)?);\n', '', text, flags=re.M)
    text = re.sub(r'^namespace [\w.]+;\n', '', text, flags=re.M)
    text = re.sub(r'\[Config\([^\n]*\n', '[System.Serializable]\n', text)
    text = re.sub(r'\[Key\(\d+\)\]\n', '', text)
    text = re.sub(r'\[MessagePackObject\([^\n]*\n', '', text)
    text = text.replace('using MessagePack;\n', '')
    text = re.sub(r'(\w+)\.Deconstruct\(ref (\w+), ref (\w+)\);', r'\2 = \1.Key; \3 = \1.Value;', text)
    return text


