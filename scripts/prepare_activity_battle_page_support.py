"""Port the original activity display controls without inventing activity state."""
import hashlib
import json
import re
from pathlib import Path

from official_apk import ROOT
from prepare_partner_input_dialog import metadata

CLIENT = ROOT / '.tools/source-packages/current/884_156692/official-code/client-source'
DESTINATION = ROOT / 'unity/Assets/Game/Runtime/Official/ActivityBattleUI'


def main():
    sources, outputs = {}, {}

    def port(name, changes):
        source = CLIENT / (name + '.cs')
        sources[source.relative_to(ROOT).as_posix()] = hashlib.sha256(source.read_bytes()).hexdigest()
        text = source.read_text('utf8')
        for old, new in changes:
            if old not in text:
                raise ValueError('Reinspect original ' + name + ': ' + old)
            text = text.replace(old, new)
        text = re.sub(r'^using (?:Common|Framework(?:\.[\w.]+)?);\n', '', text, flags=re.M)
        text = re.sub(r'\[Inject\]\s*', '', text)
        text = re.sub(r'\bStateSwitcher<', 'WorldStateSwitcher<', text)
        text = re.sub(r'\bMultiLanguageText\b', 'WorldMultiLanguageText', text)
        text = re.sub(r'\bUIBase\b', 'WorldInitializedUI', text)
        text = re.sub(r'\bShowRemainTimeInfo\b', 'WorldShowRemainTimeInfo', text)
        text = text.replace('ETimeSpanFormatType.Brief', 'WorldTimeSpanFormatType.Brief')
        text = ('// Selected official ' + name + '; generated by prepare_activity_battle_page_support.py.\n'
                'using Zjcs.Official.WorldUI;\nusing Zjcs.Official.ProfessionUI;\n'
                'namespace Zjcs.Official.ActivityBattleUI\n{\nusing Object = UnityEngine.Object;\n' + text + '\n}\n')
        target = DESTINATION / (name + '.cs')
        target.write_text(text, 'utf8', newline='\n')
        for path in (target, metadata(target)):
            outputs[path.relative_to(ROOT).as_posix()] = hashlib.sha256(path.read_bytes()).hexdigest()

    source = (CLIENT / 'MultiFontTextMaterial.cs').read_text('utf8')
    start = source.index('\t\t\tGLoggerErrorInterpolatedStringHandler')
    end = source.index('\n\t\t\tmAssetOperationHandle.Release();', start)
    port('MultiFontTextMaterial', (
        ('AssetOperationHandle<Material>', 'IProfessionAssetOperation<Material>'),
        ('private IFontAssetFontService FontAssetFontService { get; set; }',
         'private IFontAssetFontService FontAssetFontService { get; set; }'),
        ('private IResourceLoader ResourceLoader { get; set; }',
         'private IProfessionImageResourceLoader ResourceLoader { get; set; }\n\n'
         '\tpublic void Configure(IFontAssetFontService fonts, IProfessionImageResourceLoader resources)\n'
         '\t{ FontAssetFontService = fonts; ResourceLoader = resources; }'),
        (source[start:end], '\t\t\tDebug.LogError("未能找到目标字体材质:" + text, this);'),
        ('mAssetOperationHandle?.Release(tryUnloadAsset: true)', 'mAssetOperationHandle?.Dispose()'),
        ('mAssetOperationHandle.Release()', 'mAssetOperationHandle.Dispose()'),
    ))

    # The local activity adapter supplies the same name/end-date consumed by
    # the original display. No period, preview or challenge rules live here.
    source = (CLIENT / 'ActivityInfoUI.cs').read_text('utf8')
    start = source.index('\tprotected override void OnEnableAndInited()')
    end = source.index('\n\tprotected virtual void RefreshTime', start)
    port('ActivityInfoUI', (
        ('private ActivityType mActivityType;\n\n\tprivate int mId;', 'private ActivityDisplayData mData;'),
        ('Init(ActivityType activityType, int id)', 'Init(ActivityDisplayData data)'),
        ('InitPreview(ActivityType activityType, int id)', 'InitPreview(ActivityDisplayData data)'),
        ('mActivityType = activityType;\n\t\t\tmId = id;', 'mData = data;'),
        (source[start:end], '\tprotected override void OnEnableAndInited()\n\t{\n'
         '\t\tbase.OnEnableAndInited();\n'
         '\t\tif (!mPreviewMode) RefreshTime(mData);\n'
         '\t\tif (mNameTxt != null) mNameTxt.SetKey("{0}",\n'
         '\t\t\t(mNameTxt.Localizer ?? WorldMultiLanguageText.Localize)(mData.NameKey));\n\t}\n'),
        ('RefreshTime(ActivityData data)', 'RefreshTime(ActivityDisplayData data)'),
    ))

    port('ActivityDomainBossPreviewContent', (
        ('private ActivityData mMainData;', 'private System.Func<float> mPreviewProgress;\n'
         '\tpublic System.Func<DateTime> Clock { private get; set; } = () => DateTime.Now;'),
        ('\n\tprivate int mPreviewHotValueId;\n', '\n'),
        ('Init(ActivityData mainData, DateTime summonTime, int previewHotValueId, Action onSummonReached)',
         'Init(System.Func<float> previewProgress, DateTime summonTime, Action onSummonReached)'),
        ('mMainData = mainData;', 'mPreviewProgress = previewProgress ?? throw new ArgumentNullException(nameof(previewProgress));'),
        ('\n\t\tmPreviewHotValueId = previewHotValueId;', ''),
        ('TimeManager.Instance.GetDateTime()', 'Clock()'),
        ('ActivityDomainBossPreviewUtils.GetPreviewProgress(mMainData, mPreviewHotValueId)', 'mPreviewProgress()'),
        ('Formula.Instance.ToSpecifySignificantPercent(fill01, 2, LanguageManager.Instance.CurrentLanguage)',
         'Zjcs.Official.World.NativeLabelUI.Framework.NumberFormatHelper.FormatSpecifySignificantPercent(fill01, 2, "%", \'.\')'),
    ))

    path = DESTINATION / 'ActivityDisplayData.cs'
    for output in (path, metadata(path)):
        outputs[output.relative_to(ROOT).as_posix()] = hashlib.sha256(output.read_bytes()).hexdigest()
    receipt = dict(manifest='884_156692', sources=sources, outputs=outputs,
        generator_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        adaptation='Original activity title/end timer, preview fill/countdown/one-shot notification and language-font material lifecycle. '
                    'Activity data, preview progress and asset operations are supplied at existing local seams; '
                    'this port supplies no server or local activity rules. Full activity page binding and runtime verification pending.')
    (ROOT / 'assets/reference/daily-challenges/activity-page-support-source-manifest.json').write_text(
        json.dumps(receipt, ensure_ascii=False, indent=2) + '\n', 'utf8', newline='\n')


if __name__ == '__main__': main()
