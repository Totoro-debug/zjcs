"""Bind the original burning-grid table, entity and mover from one verified source."""
import hashlib
import json
from pathlib import Path

from official_apk import Apk, ROOT
from official_ec_codec import Formats
from official_map_codec import unpack
from official_tables import Constructors

OUTPUT = ROOT / 'unity/Assets/Game/Runtime/Official/Combat/FightOfficialGridItemRules.cs'
PROOF = ROOT / 'assets/reference/battle-rules/grid-items-source-manifest.json'


def identity(path):
    return dict(path=path.relative_to(ROOT).as_posix(),
                sha256=hashlib.sha256(path.read_bytes()).hexdigest())


def build():
    with Apk.current() as apk:
        code = ROOT / '.tools/source-packages/current' / apk.version / 'official-code'
        manifest = code.parent / 'code-manifest.json'
        metadata = json.loads(manifest.read_bytes())
        assembly = code / 'managed/decoded/Console.dll'
        if (metadata['manifest'] != apk.version or identity(assembly)['sha256']
                != metadata['assemblies']['Console.dll']['decoded_sha256']):
            raise ValueError('Selected grid configuration and official code identity differ')
        constructors, formats = Constructors(code), Formats(code)
        inputs = []

        def payload(bundle, suffix):
            obj = apk.asset(bundle, suffix)
            raw = obj.read().m_Script.encode('utf-8', 'surrogateescape')
            inputs.append(dict(asset=suffix, provenance=apk.provenance(obj),
                               payload_sha256=hashlib.sha256(raw).hexdigest(), bytes=len(raw)))
            return raw

        tables = constructors.table(payload('config_luban', '/grid_item.g.bytes'), 'TbGridItemInfo')
        movers = constructors.table(payload('config_luban_ec', '/EC/entity_grid_mover.g.bytes'),
                                    'TbEntityGridMoverInfo')
        entities = {key: {typ.removeprefix('Common.'): formats.component(typ, raw)
                          for typ, raw in components}
                    for parent, key, components in unpack(payload('config_ec', '/FightGridItem_part1.g.bytes'))[0]
                    if parent == 0}
        rows, cases = [], []
        for row in tables:
            if row['Id'] not in (3320, 3328):
                continue
            entity = entities[row['TempEntityId']]
            mover = entity['FightGridMoverComponent']
            ground, = [value['GroundTypes'] for value in movers
                       if value['Id'] == mover['WalkableGroundTypeKey']]
            # These selected entities have no hidden initial status/property source.
            if (entity['FightPropComponent'] or entity['FightRoleCharacterComponent']['CharacterType'] != 6
                    or entity['FightRoundComponent']['RoundType'] != 0
                    or entity['FightStatusAgentComponent']['InitStatusEntityClassIds']
                    or mover['WalkableGroundTypeServerOverrideKey'] != 0
                    or row['DestoryDelayTime'] != 0 or row['GroundType'] != 0
                    or row['ActionBehOfSameStatus'] != 1
                    or row['BlockedByTypes']):
                raise ValueError('Restore additional official grid-item behavior before binding it')
            body = entity['GridTransformComponent']['BodyRangeInfos']
            if len(body) != 1 or body[0]['Pos'] != dict(X=0, Y=0):
                raise ValueError('Restore the original multi-cell grid item')
            mask = sum(1 << value for value in set(ground))
            cases.append('''                case %d: return new FightBattleGridItemDefinition
                {
                    ClassId = %d, EntityClassId = %d, MoveMask = %d,
                    CheckGridCanStand = %s, IgnoreGridBlocked = %s,
                    DestroyOnOwnerDie = %s, DestroyOnOwnerDestroy = %s,
                    OverrideTypes = new[] { %s }
                };''' % (row['Id'], row['Id'], row['TempEntityId'], mask,
                    str(row['CheckGridCanStand']).lower(), str(row['IgnoreGridBlocked']).lower(),
                    str(row['DestoryOnOwnerDie']).lower(), str(row['DestoryOnOwnerDestory']).lower(),
                    ', '.join(map(str, row['OverrideTypes']))))
            rows.append(dict(table=row, entity=entity, walkable_ground_types=ground))
        if len(rows) != 2:
            raise ValueError('Missing original burning grid definitions')
        text = '''// Generated by scripts/prepare_battle_grid_items.py; manifest %s.
using System;

namespace Zjcs.Combat.Official
{
    public sealed class FightBattleGridItemDefinition
    {
        public int ClassId;
        public int EntityClassId;
        public int MoveMask;
        public bool CheckGridCanStand;
        public bool IgnoreGridBlocked;
        public bool DestroyOnOwnerDie;
        public bool DestroyOnOwnerDestroy;
        public int[] OverrideTypes;
    }

    public static class FightOfficialGridItemRules
    {
        public static FightBattleGridItemDefinition Get(int classId)
        {
            switch (classId)
            {
%s
                default: throw new InvalidOperationException("Unbound official grid item: " + classId);
            }
        }
    }
}
''' % (apk.version, '\n'.join(cases))
        OUTPUT.write_text(text, encoding='utf-8', newline='\n')
        meta = Path(str(OUTPUT) + '.meta')
        if not meta.exists():
            guid = hashlib.md5(('zjcs-official:' + OUTPUT.relative_to(ROOT / 'unity').as_posix()).encode()).hexdigest()
            meta.write_text('fileFormatVersion: 2\nguid: ' + guid + '\nMonoImporter:\n'
                            '  externalObjects: {}\n  serializedVersion: 2\n  defaultReferences: []\n'
                            '  executionOrder: 0\n  icon: {instanceID: 0}\n  userData:\n'
                            '  assetBundleName:\n  assetBundleVariant:\n', encoding='ascii')
        sources = {code / 'common-source/Common' / (name + '.cs') for name in constructors.sources}
        sources.update(formats.sources.values())
        sources.update(code / 'common-source/Common' / name for name in (
            'GridMoverComponentInfo.cs', 'FightRoleGridItemComponent.cs',
            'FightRoleGridItemSpawnerComponent.cs', 'FightHitSummonCfgBase.cs',
            'FightHitSummonGridItemCfg.cs', 'FightHitSummonComponentInfo.cs',
            'Pos2d.cs', 'StatusAutoRemoveComponentInfo.cs'))
        sources.update(code / 'client-source' / name for name in (
            'MyFightRoleGridItemSpawner.cs', 'MyFightRoleGridItem.cs', 'MyFightStatusMoveNear.cs'))
        PROOF.write_text(json.dumps(dict(manifest=apk.version, code_manifest=identity(manifest),
            inputs=inputs, sources=[identity(Path(path)) for path in sorted(sources)],
            assembly=identity(assembly), definitions=rows, outputs=[identity(OUTPUT), identity(meta)],
            generator=identity(Path(__file__)),
            conversion='Original table flags and entity mover mask compiled together. Empty property configuration is preserved; snapshot inheritance is a separately confirmed offline rule.',
            limits=['Only 3320/3051 and 3328/3054 are bound. This receipt does not assert runtime spawning or visual lifecycle completion.']),
            ensure_ascii=False, indent=2) + '\n', encoding='utf-8', newline='\n')
        print('Original burning grid definitions bound:', apk.version, [row['table']['Id'] for row in rows])


if __name__ == '__main__':
    build()
