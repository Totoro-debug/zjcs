"""Adapt the selected original home custom sprite mesh and alpha-group components."""
from pathlib import Path
import re

from official_apk import ROOT
from prepare_home_environment_native import metadata


def prepare():
    source = ROOT/'.tools/source-packages/current/884_156692/official-code/client-source'
    target = ROOT/'unity/Assets/Game/Runtime/Official/HomeSceneUiControls'
    for name in ('CustomRenderer','SpriteRendererGroup'):
        text = (source/(name+'.cs')).read_text('utf8')
        text = re.sub(r'^\s*//IL_.*\n','\n',text,flags=re.M)
        text = text.replace('Vector2.op_Implicit(vertices[i])','(Vector3)vertices[i]')
        text = '// Original selected application renderer; generated by prepare_home_scene_render_controls.py.\n' \
            +'namespace Zjcs.Official.HomeSceneUiControls\n{\nusing Object = UnityEngine.Object;\n'+text+'\n}\n'
        path = target/(name+'.cs')
        if path.exists() and path.read_text('utf8') != text:
            raise ValueError('Preserve existing original home renderer changes: '+str(path))
        path.write_text(text,'utf8',newline='\n')
        metadata(path,'MonoImporter')
        print('Prepared original home renderer',name)


if __name__ == '__main__':
    prepare()
