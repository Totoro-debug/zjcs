#!/usr/bin/env python3
"""Restore the original single-seat activity icon RT lifecycle and camera setup."""
import hashlib
import json
import re
from pathlib import Path

from official_apk import ROOT
from prepare_partner_input_dialog import metadata

SOURCE = ROOT / '.tools/source-packages/current/884_156692/official-code/client-source'
TARGET = ROOT / 'unity/Assets/Game/Runtime/Official/ActivityBattleUI'


def main():
    inputs, outputs = {}, {}
    digest = lambda path: hashlib.sha256(path.read_bytes()).hexdigest()

    def read(name):
        path = SOURCE / name
        inputs[path.relative_to(ROOT).as_posix()] = digest(path)
        return path.read_text('utf8')

    def save(name, text):
        text = '\n'.join(line for line in text.splitlines() if '//IL_' not in line) + '\n'
        path = TARGET / name
        path.write_text('// Original official RT UI; generated by prepare_activity_rt_ui.py.\n'
            'namespace Zjcs.Official.ActivityBattleUI\n{\n' + text + '}\n', 'utf8', newline='\n')
        for item in (path, metadata(path)):
            outputs[item.relative_to(ROOT).as_posix()] = digest(item)

    def once(text, old, new):
        if text.count(old) != 1:
            raise ValueError('Reinspect original RT UI: ' + old)
        return text.replace(old, new)

    save('ISpineRTUI.cs', read('ISpineRTUI.cs'))
    save('ISpineRTUIManager.cs', read('ISpineRTUIManager.cs').replace(
        'using Framework;', 'using Zjcs.Official.ProfessionUI;'))
    save('IUIBloomRequirer.cs', read('IUIBloomRequirer.cs'))

    text = read('SpineRTUIManager.cs')
    text = text.replace('using Framework;', 'using System;\nusing Zjcs.Official.ProfessionUI;')
    text = text.replace('using GameFramework;\n', '')
    text = once(text, 'SceneScopeBackgroundServiceBase, ISpineRTUIManager, IMapScopeBackgroundService, IFightScopeBackgroundService, IHomeScopeBackgroundService',
        'ISpineRTUIManager, IDisposable')
    text = once(text, 'RTHandle.op_Implicit(mSpineRTUI.RTColorTextureHandle)', '(UnityEngine.Texture)mSpineRTUI.RTColorTextureHandle')
    text = once(text, 'protected override void Dispose()', 'public void Dispose()')
    text = once(text, '\t\tbase.Dispose();\n', '')
    save('SpineRTUIManager.cs', text)

    text = read('TempRTUI.cs')
    for line in ('using AppearanceSystem;', 'using AppearanceSystem.Runtime;', 'using Framework;',
            'using Framework.DependencyInjection;', 'using Framework.Logging;',
            'using Framework.Logging.InterpolatedStringHandler;'):
        text = once(text, line + '\n', '')
    begin = text.index('\t[Inject]\n')
    end = text.index('\n\tpublic int TargetKey', begin)
    text = text[:begin] + '\t[System.NonSerialized] public IActivityRtUIBindings Bindings;\n' + text[end:]
    text = once(text, '\t\tCreateCamera();',
        '\t\tif (Bindings == null) throw new System.InvalidOperationException("Bind the original RT UI services before Awake.");\n\t\tCreateCamera();')
    text = once(text, 'ServiceProviderExtensions.Instantiate(((Component)(object)mRTCamera).GetSceneContainer(), RTTarget, ((Component)mRTCamera).transform, false)',
        'Bindings.InstantiateTarget(RTTarget, mRTCamera.transform)')
    begin = text.index('\t\t\tGLoggerErrorInterpolatedStringHandler message =')
    end = text.index('\n\t\t\tval2 = (GraphicsFormat)4;', begin)
    text = text[:begin] + '\t\t\tDebug.LogError("Not supported graphics format: " + val2);' + text[end:]
    text = once(text, 'RenderTargetIdentifier.op_Implicit(mRTColorTextureId)', 'new RenderTargetIdentifier(mRTColorTextureId)')
    text = once(text, 'ReAllocateIfNeeded(ref mRTColorTextureHandle, ref descriptor,',
        'ReAllocateIfNeeded(ref mRTColorTextureHandle, in descriptor,')
    text = once(text, '\t\tAppearanceRendererLite appearanceRendererLite = default;\n\t\tif (mInstance.TryGetComponent<AppearanceRendererLite>(ref appearanceRendererLite))\n\t\t{\n\t\t\tMaterial[] independentMaterials = appearanceRendererLite.GetIndependentMaterials();',
        '\t\tMaterial[] independentMaterials = Bindings.GetIndependentMaterials(mInstance);\n\t\tif (independentMaterials != null)\n\t\t{')
    text = once(text, 'AppearanceMaterialUtils.sLightAtten', 'Shader.PropertyToID("_LightAtten")')
    text = text.replace('SpineRTUIManager.', 'Bindings.RenderSeats.')
    text = once(text, 'UIBloomManager.RegisterRequirer(this);', 'Bindings.RegisterBloom(this);')
    text = once(text, 'UIBloomManager.UnregisterRequirer(this);', 'Bindings.UnregisterBloom(this);')
    text = once(text, 'Object.op_Implicit((Object)(object)mRTCamera)', 'mRTCamera')
    text = once(text, 'RTHandle.op_Implicit(mRTColorTextureHandle)', '(Texture)mRTColorTextureHandle')

    # Copy the original shared camera helper verbatim, with only operator/API
    # syntax repaired. The RT component keeps its subsequent camera assignments.
    camera = read('CameraUtils.cs')
    begin = camera.index('\tpublic static Camera CreateRTCamera()')
    end = camera.index('\n\t}', begin) + len('\n\t}')
    helper = camera[begin:end].replace('public static Camera CreateRTCamera()', 'private static Camera CreateRTCamera()')
    helper = once(helper, 'LayerMask.op_Implicit(0)', '(LayerMask)0')
    text = once(text, 'CameraUtils.CreateRTCamera()', 'CreateRTCamera()')
    # Two official methods have the same name. Rename only the helper declaration
    # and its call to keep the component setup callback intact.
    helper = once(helper, 'private static Camera CreateRTCamera()', 'private static Camera CreateOriginalRTCamera()')
    text = once(text, 'mRTCamera = CreateRTCamera();', 'mRTCamera = CreateOriginalRTCamera();')
    text = text.rstrip()[:-1] + '\n' + helper + '\n}\n'
    save('TempRTUI.cs', text)
    save('IActivityRtUIBindings.cs', '''using UnityEngine;

// Explicit replacements for the original scene-container injection boundaries.
// Returning null materials preserves the original absent-AppearanceRendererLite branch.
public interface IActivityRtUIBindings
{
    ISpineRTUIManager RenderSeats { get; }
    GameObject InstantiateTarget(GameObject template, Transform parent);
    Material[] GetIndependentMaterials(GameObject instance);
    void RegisterBloom(IUIBloomRequirer requirer);
    void UnregisterBloom(IUIBloomRequirer requirer);
}
''')
    inputs[Path(__file__).relative_to(ROOT).as_posix()] = digest(Path(__file__))
    proof = dict(manifest='884_156692', inputs=inputs, outputs=outputs,
        adaptation='Retain official render-seat ownership, matching-target reuse, reentrant SafeAction notifications, '
            'enable/disable/destruction order, camera settings, target position/scale, RT formats and particle material updates. '
            'Reuse the migrated official SafeAction. Replace the scene background-service owner with explicit IDisposable. '
            'Expose only existing scene injection boundaries through IActivityRtUIBindings; restore decompiler C# API syntax.',
        scope='Lifecycle and render pass are migrated; production service, 3706 model/animation/particle binding and rendered validation remain pending.')
    (ROOT / 'assets/reference/daily-challenges/activity-rt-ui-source-manifest.json').write_text(
        json.dumps(proof, ensure_ascii=False, indent=2) + '\n', 'utf8', newline='\n')


if __name__ == '__main__': main()
