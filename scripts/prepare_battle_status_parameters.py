"""Extract original status accessor types/inheritance; record the offline adapter inputs."""
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CURRENT = ROOT / '.tools/source-packages/current/884_156692'
SOURCE = CURRENT / 'official-code/common-source/Common'
TARGET = ROOT / 'unity/Assets/Game/Runtime/Official/Combat/FightOfficialCombatCatalog.StatusParameterFields.cs'


def identity(path):
    raw = path.read_bytes()
    return dict(path=path.relative_to(ROOT).as_posix(), bytes=len(raw),
                sha256=hashlib.sha256(raw).hexdigest())


def write(path, text):
    raw = text.encode('utf-8')
    with path.open('r+b' if path.exists() else 'wb') as stream:
        stream.write(raw)
        stream.truncate()


def main():
    receipt = CURRENT / 'code-manifest.json'
    code = json.loads(receipt.read_bytes())
    assembly = CURRENT / 'official-code/managed/decoded/Console.dll'
    assert code['manifest'] == '884_156692'
    assert identity(assembly)['sha256'] == code['assemblies']['Console.dll']['decoded_sha256']
    classes = {}
    paths = {}
    info_paths = set()

    def field_type(info, field):
        path = SOURCE / (info + '.cs')
        source = path.read_text(encoding='utf-8-sig')
        info_paths.add(path)
        declaration = re.search(r'public (float|int|long) ' + re.escape(field) + r'\b', source)
        if declaration:
            return declaration[1][0]
        parent = re.search(r'class ' + re.escape(info) + r'\s*:\s*(\w+)', source)
        assert parent, (info, field)
        return field_type(parent[1], field)

    for path in sorted(SOURCE.glob('*Component.cs')):
        source = path.read_text(encoding='utf-8-sig')
        match = re.search(r'public (?:abstract |sealed )?class (\w+)(?:<[^>]+>)?\s*:\s*(\w+)', source)
        if not match:
            continue
        fields = {}
        for call in re.finditer(r'GetPropertyReplaceValue\("(\w+)",\s*Info\.(\w+)\)', source):
            assert call[1] == call[2], (path, call[0])
            # Overload selection follows Info's declared field type. Some original
            # public getters return float while calling the int overload.
            fields[call[1]] = field_type(match[1] + 'Info', call[2])
        classes[match[1]] = (match[2], fields)
        paths[match[1]] = path

    used = set()

    def inherited(name, visited=()):
        if name not in classes:
            return {}
        assert name not in visited, name
        parent, own = classes[name]
        # The generic base and its non-generic base share one decompiled file/name.
        if parent == name:
            if own:
                used.add(paths[name])
            return own
        result = inherited(parent, visited + (name,)) | own
        if result:
            used.add(paths[name])
        return result

    fields = {name: inherited(name) for name in classes if inherited(name)}
    assert len(fields) == 53 and sum(map(len, fields.values())) == 120
    assert fields['FightStatusGlobalRoundUpdateComponent']['MaxInvokeCount'] == 'i'
    assert fields['FightStatusRoleSummonCountComponent']['LimitCount'] == 'i'
    lines = ['// Generated by scripts/prepare_battle_status_parameters.py from original accessors.',
             'namespace Zjcs.Combat.Official', '{', '    public sealed partial class FightOfficialCombatCatalog',
             '    {', '        private static string StatusParameterFields(string component)',
             '        {', '            switch (component)', '            {']
    for name, values in fields.items():
        tokens = ' '.join(kind + name for name, kind in values.items())
        lines.append(f'                case "{name}": return "{tokens}";')
    lines.extend(['                default: return null;', '            }', '        }', '    }', '}', ''])
    write(TARGET, '\n'.join(lines))
    used.update(SOURCE / (name + '.cs') for name in ('FightStatusBaseComponent', 'FightStatusUtilsHandler', 'Formula'))
    used.update(info_paths)
    proof = dict(code_manifest='884_156692', configuration_manifest='854_156383',
                 code_receipt=identity(receipt), assembly=identity(assembly),
                 original=[identity(path) for path in sorted(used)],
                 input=identity(ROOT / 'unity/Assets/Official/Combat/battle-rules.json'),
                 adapter=[identity(path) for path in (TARGET, TARGET.with_name('FightOfficialCombatCatalog.StatusParameters.cs'),
                     TARGET.with_name('FightOfficialCombatCatalog.StatusReplay.cs'), TARGET.with_name('FightOfficialCombatCatalog.cs'))],
                 validation=identity(ROOT / 'scripts/test_battle_status_parameters.ps1'),
                 play_mode=identity(ROOT / 'unity/Assets/Game/Editor/HomeBattleHostPlayModeAcceptance.StatusReplay.cs'),
                 generator=identity(Path(__file__).resolve()),
                 operation='Extract 53 original component accessor contracts (120 inherited fields). '
                     'Resolve typed status replacement parameters on per-instance configuration copies '
                     'before existing status parsers; preserve first-match lookup, missing defaults, '
                     'fixed-point conversion and original integer narrowing. Unknown mappings remain '
                     'visible to unsupported-rule guards. This does not implement missing component execution.')
    write(ROOT / 'assets/reference/battle-rules/status-parameters-source-manifest.json',
          json.dumps(proof, ensure_ascii=False, indent=2) + '\n')
    print('Recorded 53 original component contracts / 120 inherited parameter fields.')


if __name__ == '__main__':
    main()
