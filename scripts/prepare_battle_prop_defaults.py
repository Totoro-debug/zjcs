"""Compile the pinned official LevelPropDefaultValue table into the pure combat assembly."""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from official_apk import Apk, ROOT
from official_tables import Constructors


def sha(data):
    return hashlib.sha256(data).hexdigest()


def build():
    apk = Apk()
    asset_path, pointer = next((path, ptr) for path, ptr in apk.container("config_luban")
                               if path.endswith("/level_prop_default_value.g.bytes"))
    entry = {"path": asset_path, "bundle": "defaultpackage_assets_config_luban.bundle"}
    obj = pointer.deref()
    raw = obj.read().m_Script.encode("utf-8", "surrogateescape")
    rows = Constructors().table(raw, "TbLevelPropDefaultValue")
    groups = {}
    for row in rows:
        groups.setdefault((row["DefaultValue"], tuple(row["PropTypes"])), []).append(row["ClassId"])
    sections = []
    for (value, properties), ids in groups.items():
        sections.append("            if (" + " || ".join("classId == " + str(i) for i in ids) + ")\n"
                        + "                AddMissing(properties, new[] { " + ", ".join(map(str, properties))
                        + " }, " + str(value) + "L);")
    code = """// Generated by scripts/prepare_battle_prop_defaults.py from the verified 854_156383 table.
// Official LevelPropParser.TryGetPropDict: insert defaults only for absent keys.
using System.Collections.Generic;

namespace Zjcs.Combat.Official
{
    internal static class FightOfficialLevelPropDefaults
    {
        public static void Apply(int classId, Dictionary<int, long> properties)
        {
""" + "\n".join(sections) + """
        }

        private static void AddMissing(Dictionary<int, long> values, int[] ids, long value)
        {
            foreach (int id in ids)
                if (!values.ContainsKey(id)) values.Add(id, value);
        }
    }
}
"""
    output = ROOT / "unity/Assets/Game/Runtime/Official/Combat/FightOfficialLevelPropDefaults.cs"
    receipt = ROOT / "assets/reference/battle-rules/prop-defaults-source-manifest.json"
    if output.exists() and sha(output.read_bytes()) != json.loads(receipt.read_bytes())["output_sha256"]:
        raise ValueError("Refusing to overwrite modified level-prop defaults")
    output.write_bytes(code.encode())
    sources = []
    for name in ("LevelPropParser", "LevelPropDefaultValue", "TbLevelPropDefaultValue"):
        path = ROOT / ".tools/source-packages/official-code/common-source/Common" / (name + ".cs")
        sources.append({"path": path.relative_to(ROOT).as_posix(), "sha256": sha(path.read_bytes())})
    receipt.write_text(json.dumps({"manifest": "854_156383", "asset": entry, "source": apk.provenance(obj),
                                  "input_sha256": sha(raw), "code": sources, "row_count": len(rows),
                                  "output": output.relative_to(ROOT).as_posix(), "output_sha256": sha(output.read_bytes()),
                                  "generator_sha256": sha(Path(__file__).read_bytes())}, indent=2) + "\n", encoding="utf-8")
    print("Recovered official property defaults:", len(rows))


if __name__ == "__main__":
    build()
