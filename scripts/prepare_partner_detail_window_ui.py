def replace(text, old, new):
    if old not in text:
        raise ValueError('Official source adaptation anchor changed: ' + old)
    return text.replace(old, new)


def controller(name):
    text = (SOURCE / (name + '.cs')).read_text('utf8')
    text = re.sub(r'^using (?:AppearanceSystem(?:\.Runtime)?|Common|Framework(?:\.[\w.]+)?|Spine\.Unity|R3);\n', '', text, flags=re.M)
    text = re.sub(r'^\s*//IL_.*\n', '\n', text, flags=re.M)
    text = re.sub(r'\[UIWindow\([^\n]+\)\]\n', '', text)
    text = text.replace('using UnityEngine.UI.Ext;\n', '')
    text = text.replace('StateSwitcher<', 'WorldStateSwitcher<')
    return text


def inject(text, service):
    return re.sub(r'\t\[Inject\]\n\tprivate .*?\{ get; set; \}\n', '', text).replace(
        '\n\tprivate void Awake()',
        '\n    private ' + service + ' services;\n'
        '    public void Configure(' + service + ' value)\n'
        '    { services = value ?? throw new System.ArgumentNullException(nameof(value)); }\n'
        '\n\tprivate void Awake()', 1)


