#!/usr/bin/env python3
"""Migrate the original activity icon offscreen pass without changing its draw order."""
import hashlib
import json
import re
from pathlib import Path

from official_apk import ROOT
from prepare_partner_input_dialog import metadata


def main():
    source = ROOT / '.tools/source-packages/current/884_156692/official-code/client-source/SimpleRTRenderPass.cs'
    text = source.read_text('utf8')
    def replace(old, new):
        nonlocal text
        if text.count(old) != 1: raise ValueError('Reinspect original RT render pass: ' + old)
        text = text.replace(old, new)
    replace('RTHandles.Alloc(RenderTargetIdentifier.op_Implicit(ShaderConstants.sRTDepth), "_RTDepth")',
        'RTHandles.Alloc(new RenderTargetIdentifier(ShaderConstants.sRTDepth), "_RTDepth")')
    replace('camera.TryGetCullingParameters(ref val);', 'camera.TryGetCullingParameters(out val);')
    replace('ReAllocateIfNeeded(ref mDepthHandle, ref compatibleDescriptor,',
        'ReAllocateIfNeeded(ref mDepthHandle, in compatibleDescriptor,')
    # The original call sites both select the RenderTargetIdentifier conversion,
    # not the Texture conversion also provided by RTHandle.
    if text.count('RTHandle.op_Implicit(mRTHandle)') != 2:
        raise ValueError('Reinspect original RT handle conversions')
    text = text.replace('RTHandle.op_Implicit(mRTHandle)', '(RenderTargetIdentifier)mRTHandle')
    replace('RTHandle.op_Implicit(mDepthHandle)', '(RenderTargetIdentifier)mDepthHandle')
    replace('((IDisposable)val4/*cast due to constrained. prefix*/).Dispose();', '((IDisposable)val4).Dispose();')
    text = '\n'.join(line for line in text.splitlines() if '//IL_' not in line) + '\n'
    text = re.sub(r'\n\tstatic SimpleRTRenderPass\(\)\n\t\{\s*\}\n', '\n', text)
    text = ('// Original SimpleRTRenderPass; generated by prepare_activity_rt_render_pass.py.\n'
        'namespace Zjcs.Official.ActivityBattleUI\n{\n' + text + '}\n')
    target = ROOT / 'unity/Assets/Game/Runtime/Official/ActivityBattleUI/SimpleRTRenderPass.cs'
    target.write_text(text, 'utf8', newline='\n')
    digest = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()
    proof = dict(manifest='884_156692',
        inputs={p.relative_to(ROOT).as_posix(): digest(p) for p in (source, Path(__file__))},
        outputs={p.relative_to(ROOT).as_posix(): digest(p) for p in (target, metadata(target))},
        adaptation='Retain original descriptor, graphics formats, layer masks, Universal2D tag, sorting, culling, '
            'view/projection, clear, draw, depth ownership and disposal order. Restore C# out parameter and '
            'in descriptor and explicit RenderTargetIdentifier conversions; remove decompiler-only comments and empty constructor.',
        scope='Original offscreen pass only. TempRTUI, model/animation/particle binding and runtime rendering pending.')
    (ROOT / 'assets/reference/daily-challenges/activity-rt-render-pass-source-manifest.json').write_text(
        json.dumps(proof, ensure_ascii=False, indent=2) + '\n', 'utf8', newline='\n')


if __name__ == '__main__': main()
